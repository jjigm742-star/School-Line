'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const s = require('../server');
const root = path.join(__dirname, '..');
const notes = JSON.parse(fs.readFileSync(path.join(root,'public/latest-patch.json'),'utf8'));
assert.equal(notes.title,'《스쿨라인》 1.11 — 운동장과 전투 다양성 업데이트');
assert.deepEqual(notes.sections.map(x=>x.heading),['1. 신규 맵','2. 캐릭터 밸런스','3. 접속 안정화 및 최적화']);
const [map,balance]=notes.sections;
assert.deepEqual(map.groups[0].items.map(x=>x.name),['《운동장》','힐팩','랜덤 맵']);
assert.deepEqual(balance.groups.map(x=>x.label),['버프 🟢','너프 🔴','리워크 🟣']);
assert.deepEqual(balance.groups.map(x=>x.tone),['buff','nerf','rework']);
assert.deepEqual(balance.groups.map(x=>x.items.length),[8,2,1]);
assert.deepEqual(balance.groups[0].items.map(x=>x.name),['마그넷','슈터','레이저','아이스','포이즌','러너','라이트','윈드']);
assert.deepEqual(balance.groups[1].items.map(x=>x.name),['쉴드','파이어']);
assert.equal(balance.groups[2].items[0].name,'위치');
assert.equal(balance.groups[0].items.find(x=>x.name==='러너').text,'기본 DPS 65 → 70 (1발당 피해 13 → 14)');
assert.equal(balance.groups[2].items[0].text,'궁극기 「마법약」을 즉시 발동 궁극기로 변경. 거리와 상관없이 살아 있는 모든 적에게 5초간 저주(받는 피해 +25%)와 이동속도 1단계 감소를 적용합니다.');
assert.deepEqual(notes.sections[2].groups[0].items.map(x=>x.name),['자동 재접속','연결 안정화','화면 동기화 개선']);
const client=fs.readFileSync(path.join(root,'public/game.js'),'utf8');
const css=fs.readFileSync(path.join(root,'public/style.css'),'utf8');
assert.match(client,/group\.tone === 'rework'/);
assert.match(css,/\.latest-patch-group h4\.rework/);
const old=JSON.parse(fs.readFileSync(path.join(root,'data/patch_notes/1.10.json'),'utf8'));
const backup=s.competitiveStatsBackupPayload();
assert.deepEqual(backup.patchNotesByVersion['1.10'],old);
assert.deepEqual(backup.patchNotesByVersion['1.11'],notes);
console.log('1.11 exact edited patch notes and archived backup PASSED');
