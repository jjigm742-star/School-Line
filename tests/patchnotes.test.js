'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const s = require('../server');
const root = path.join(__dirname, '..');
const original = JSON.parse(fs.readFileSync(path.join(root, 'data/patch_notes/1.10.json'), 'utf8'));
const current = JSON.parse(fs.readFileSync(path.join(root, 'public/latest-patch.json'), 'utf8'));
const backup = s.competitiveStatsBackupPayload();
const stats = s.publicCompetitiveStats();
assert.equal(original.version, '1.10');
assert.equal(current.version, '1.11');
assert.deepEqual(backup.patchNotesByVersion['1.10'], original);
assert.deepEqual(backup.patchNotesByVersion['1.11'], current);
assert.deepEqual(stats.patchNotesByVersion['1.10'], original);
assert.deepEqual(stats.patchNotesByVersion['1.11'], current);
assert.equal(stats.currentBuild.balanceVersion, '1.11');
assert.equal(backup.backupMeta.currentBalanceVersion, '1.11');
assert.equal(backup.schemaVersion, 7);
assert.ok(Array.isArray(backup.matches));
assert.equal(Object.prototype.hasOwnProperty.call(backup.versions, '1.11'), true);
const html = fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const js = fs.readFileSync(path.join(root,'public/game.js'),'utf8');
assert.match(html, /id="competitiveStatsPatchNotes"/);
assert.match(js, /\$\('competitiveStatsPatchNotes'\)\.onclick = openArchivedPatchNotes/);
assert.match(js, /latestPatchReturnFocus = \$\('competitiveStatsPatchNotes'\)/);
console.log('1.11 patch note archival and backup tests PASSED');
